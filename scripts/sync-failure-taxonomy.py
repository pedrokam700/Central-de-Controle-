"""Compile the one Python/Excel taxonomy configuration for the browser (no runtime fetch)."""
import json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'ames/factory-engine'))
from core.failure_taxonomy import configuration
text='// Generated by scripts/sync-failure-taxonomy.py; edit factory-engine/config only.\nexport default '+json.dumps(configuration(),ensure_ascii=False,indent=2)+';\n'
target=ROOT/'ames/data/failure-taxonomy-rules.mjs'
if '--check' in sys.argv:
    if target.read_text()!=text:raise SystemExit('Taxonomy configuration drift: run scripts/sync-failure-taxonomy.py')
else:target.write_text(text)
